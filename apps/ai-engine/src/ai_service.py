@app.get("/api/ai/dashboard")
async def get_ai_dashboard(
    _enabled: Annotated[None, Depends(require_simulation_enabled)],
) -> dict[str, Any]:
    """Simulated dashboard overview. Every figure is randomly generated."""
    try:
        # Generate dashboard data
        symbols = ["AITBC/ETH", "AITBC/ETH", "AITBC/USDT"]
        dashboard_data = {
            "market_overview": {
                "total_volume": np.random.uniform(100000, 1000000),
                "active_symbols": len(symbols),
                "ai_models_active": 3,
                "last_update": datetime.now(UTC),
            },
            "symbol_analysis": {},
        }

        for symbol in symbols:
            analysis = await ai_engine.analyze_market(symbol)
            dashboard_data["symbol_analysis"][symbol] = {
                "price": analysis["current_price"],
                "change": analysis["price_change_24h"],
                "signal": (await ai_engine.make_trading_decision(symbol))["signal"],
                "confidence": (await ai_engine.make_trading_decision(symbol))["confidence"],
            }
        logger.info("AI dashboard generated", extra={"symbols": len(symbols)})
        return {"status": "success", "dashboard": dashboard_data, "timestamp": datetime.now(UTC)}
    except Exception:
        logger.exception("AI dashboard generation failed")
        return {"status": "error", "message": "Analysis failed"}


