#!/usr/bin/env python3
"""
AITBC AI Service - Simplified Version
Basic AI-powered trading and analytics
"""

import hmac
import os
from datetime import UTC, datetime
from typing import Annotated, Any

import numpy as np
from fastapi import Depends, FastAPI, HTTPException, status
from fastapi.security import HTTPAuthorizationCredentials, HTTPBearer
from pydantic import BaseModel

from aitbc.aitbc_logging import configure_logging, get_logger  # noqa: E402

configure_logging(level="INFO")
logger = get_logger(__name__)
app = FastAPI(title="AITBC AI Service API", version="1.0.0")

# This service has no model behind it. Every figure it returns -- price, RSI, MACD,
# volatility, sentiment, and the buy/sell/hold signal derived from them -- is drawn from
# np.random. Callers cannot tell that from the response shape, so serving it is off by
# default and every payload is labelled.
ALLOW_SIMULATION = os.getenv("AI_ENGINE_ALLOW_SIMULATION", "false").lower() == "true"
SIMULATION_NOTICE = (
    "Values are randomly generated by a placeholder engine, not derived from market data "
    "or any trained model. Do not use for trading decisions."
)

security = HTTPBearer(auto_error=False)
API_KEY = os.getenv("AI_ENGINE_API_KEY", "")
REQUIRE_AUTH = os.getenv("AI_ENGINE_REQUIRE_AUTH", "true").lower() == "true"


def verify_auth(credentials: Annotated[HTTPAuthorizationCredentials, Depends(security)]) -> bool:
    """Verify the caller's bearer token when auth is required."""
    if not REQUIRE_AUTH:
        return True
    if not credentials:
        raise HTTPException(status_code=status.HTTP_401_UNAUTHORIZED, detail="Missing authentication credentials")
    if not API_KEY:
        raise HTTPException(status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail="AI engine key not configured")
    if not hmac.compare_digest(credentials.credentials, API_KEY):
        raise HTTPException(status_code=status.HTTP_403_FORBIDDEN, detail="Invalid authentication credentials")
    return True


def require_simulation_enabled() -> None:
    """Refuse to serve fabricated analysis unless it has been explicitly opted into."""
    if not ALLOW_SIMULATION:
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail=(
                "AI engine is a placeholder with no model wired up. " + SIMULATION_NOTICE + " "
                "Set AI_ENGINE_ALLOW_SIMULATION=true to receive simulated responses."
            ),
        )


# Models
# Models
class TradingRequest(BaseModel):
    symbol: str
    strategy: str = "ai_enhanced"


class AnalysisRequest(BaseModel):
    symbol: str
    analysis_type: str = "full"


# Simple AI Engine
class SimpleAITradingEngine:
    """Simplified AI trading engine"""

    def __init__(self) -> None:
        self.models_loaded = True
        logger.info("SimpleAITradingEngine initialized")

    async def analyze_market(self, symbol: str) -> dict[str, Any]:
        """Simple market analysis"""
        # Generate realistic-looking analysis
        current_price = np.random.uniform(0.001, 0.01)
        price_change = np.random.uniform(-0.05, 0.05)

        return {
            "symbol": symbol,
            "current_price": current_price,
            "price_change_24h": price_change,
            "volume_24h": np.random.uniform(1000, 10000),
            "rsi": np.random.uniform(30, 70),
            "macd": np.random.uniform(-0.01, 0.01),
            "volatility": np.random.uniform(0.01, 0.05),
            "ai_predictions": {
                "price_prediction": {
                    "predicted_change": np.random.uniform(-0.02, 0.02),
                    "confidence": np.random.uniform(0.7, 0.9),
                },
                "risk_assessment": {"risk_score": np.random.uniform(0.2, 0.8), "volatility": np.random.uniform(0.01, 0.05)},
                "sentiment_analysis": {
                    "sentiment_score": np.random.uniform(-1.0, 1.0),
                    "overall_sentiment": np.random.choice(["bullish", "bearish", "neutral"]),
                },
            },
            "timestamp": datetime.now(UTC),
        }

    async def make_trading_decision(self, symbol: str) -> dict[str, Any]:
        """Make AI trading decision"""
        analysis = await self.analyze_market(symbol)

        # Simple decision logic
        price_pred = analysis["ai_predictions"]["price_prediction"]["predicted_change"]
        sentiment = analysis["ai_predictions"]["sentiment_analysis"]["sentiment_score"]
        risk = analysis["ai_predictions"]["risk_assessment"]["risk_score"]

        # Calculate signal strength
        signal_strength = (price_pred * 0.5) + (sentiment * 0.3) - (risk * 0.2)

        if signal_strength > 0.2:
            signal = "buy"
        elif signal_strength < -0.2:
            signal = "sell"
        else:
            signal = "hold"

        confidence = abs(signal_strength)
        quantity = 1000 * confidence  # Base position size

        return {
            "symbol": symbol,
            "signal": signal,
            "confidence": confidence,
            "quantity": quantity,
            "price": analysis["current_price"],
            "reasoning": f"Signal strength: {signal_strength:.3f}",
            "timestamp": datetime.now(UTC),
        }


# Global AI engine
ai_engine = SimpleAITradingEngine()


@app.post("/api/ai/analyze")
async def analyze_market(
    request: AnalysisRequest,
    _enabled: Annotated[None, Depends(require_simulation_enabled)],
) -> dict[str, Any]:
    """Simulated market analysis. Values are randomly generated, not real."""
    try:
        analysis = await ai_engine.analyze_market(request.symbol)
        logger.info("Simulated market analysis returned", extra={"symbol": request.symbol})
        return {
            "status": "success",
            "simulated": True,
            "notice": SIMULATION_NOTICE,
            "analysis": analysis,
            "timestamp": datetime.now(UTC),
        }
    except Exception:
        logger.exception("Market analysis failed", extra={"symbol": request.symbol})
        return {"status": "error", "message": "Analysis failed"}


@app.post("/api/ai/trade")
async def execute_ai_trade(
    request: TradingRequest,
    _authenticated: Annotated[bool, Depends(verify_auth)],
    _enabled: Annotated[None, Depends(require_simulation_enabled)],
) -> dict[str, Any]:
    """Simulated trading decision. The signal is derived from random values, not a model.

    Despite the name this executes nothing -- it returns a buy/sell/hold suggestion with a
    position size. It previously did so unauthenticated and unlabelled, so a caller had no
    way to know the recommendation was fabricated.
    """
    try:
        decision = await ai_engine.make_trading_decision(request.symbol)
        logger.info("Simulated trade decision returned", extra={"symbol": request.symbol, "signal": decision["signal"]})
        return {
            "status": "success",
            "simulated": True,
            "notice": SIMULATION_NOTICE,
            "executed": False,
            "decision": decision,
            "timestamp": datetime.now(UTC),
        }
    except Exception:
        logger.exception("AI trade decision failed", extra={"symbol": request.symbol})
        return {"status": "error", "message": "Analysis failed"}


