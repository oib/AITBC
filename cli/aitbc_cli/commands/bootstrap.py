"""Bootstrap commands for builder environments (v0.16.1 §B1)."""

from __future__ import annotations

import os
from pathlib import Path

import click

from ..config import get_config
from ..services.env_validator import validate_env
from ..utils import output, success, warning


@click.group(
    epilog="""Examples:

  aitbc bootstrap bootstrap-env

  aitbc bootstrap bootstrap-env --output /tmp/.env"""
)
def bootstrap():
    """Generate starter environment and configuration files for AITBC development."""
    pass


@bootstrap.command(
    "bootstrap-env",
    epilog="""Examples:

  aitbc bootstrap bootstrap-env

  aitbc bootstrap bootstrap-env --output /tmp/.env --overwrite""",
)
@click.option("--output", "output_path", default=".env", help="Output .env file path")
@click.option("--overwrite", is_flag=True, help="Overwrite existing .env")
@click.pass_context
def bootstrap_env(ctx, output_path: str, overwrite: bool):
    """Generate a starter .env file and validate it, optionally overwriting an existing one."""
    target = Path(output_path)
    if target.exists() and not overwrite:
        warning(f"{output_path} already exists; use --overwrite to replace")
        ctx.exit(1)

    coordinator_url = get_config().coordinator_api_url or "http://localhost:8203"
    lines = [
        "# AITBC builder environment - generated by aitbc bootstrap-env",
        "# Set real values before running services",
        "",
        "AITBC_API_KEY=",
        f"COORDINATOR_API_URL={coordinator_url}",
        "",
        "# Optional service keys",
        "# OPENAI_API_KEY=",
        "# EXCHANGE_API_KEY=",
        "",
    ]
    # The file is about to hold API-key slots the operator fills in —
    # create it owner-only regardless of umask, and tighten the mode on
    # --overwrite of a pre-existing world-readable file.
    fd = os.open(target, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    os.chmod(target, 0o600)

    # Read back as a dict and validate the template (it will be missing required keys).
    env: dict[str, str] = {}
    for line in lines:
        if line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        env[key.strip()] = value.strip()

    result = validate_env(env, allow_missing=True)

    if ctx.obj["output"] == "table":
        success(f"Starter .env written to {output_path} (mode 0600)")
        if result.missing:
            warning(f"Fill in missing keys: {', '.join(result.missing)}")

    output(
        {
            "output_path": str(target.resolve()),
            "missing": result.missing,
            "valid": result.valid,
            "status": "generated",
        },
        ctx.obj["output"],
    )
