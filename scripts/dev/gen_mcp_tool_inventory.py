#!/usr/bin/env python3
"""Generate docs/reference/mcp-tool-inventory.md — one row per @mcp.tool.

Walks every ``mcp-server/*.py`` module with an AST pass: each function
decorated with ``@mcp.tool`` is a row, classified by the first call it makes
to a known dispatch helper:

- ``_http_read_tool`` / ``_http_write_tool`` / ``_run_http`` / the
  ``_call_zk`` / ``_call_liquidity`` wrappers  -> kind ``rpc``
- ``_aitbc_cli_read_tool`` / ``_run_aitbc_cli_write`` / ``_run_aitbc_cli`` /
  ``run_aitbc_command`` / ``_build_aitbc_cli_command`` -> kind ``cli``
- anything in a ``aitbc_mcp_cli_tools_generated*.py`` module -> ``generated``
  (the literals are still extracted so the row shows the wrapped command)
- no recognized dispatch call -> ``other``

The literal column carries the dispatch target: ``/rpc/...`` for
blockchain-rpc HTTP tools, ``<service>:<path>`` for other HTTP services,
``aitbc <group> <subcommand...>`` for CLI tools, ``—`` for generic pivots
(``run_aitbc_cli`` etc. take the command from the caller).

This module is also imported by ``scripts/ci/check-mcp-tool-surface.py`` so
the validator checks the exact literals the inventory prints.

Usage:
    python3 scripts/dev/gen_mcp_tool_inventory.py           # rewrite the doc
    python3 scripts/dev/gen_mcp_tool_inventory.py --check   # exit 1 if stale
"""

from __future__ import annotations

import argparse
import ast
import sys
from dataclasses import dataclass, field
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
MCP_DIR = REPO / "mcp-server"
OUT = REPO / "docs" / "reference" / "mcp-tool-inventory.md"
MARKER = "<!-- generated by scripts/dev/gen_mcp_tool_inventory.py — do not edit -->"

GENERATED_PREFIX = "aitbc_mcp_cli_tools_generated"

# Dispatch-helper signatures: helper name -> how to read its arguments.
#   http=(service_pos, path_pos, method_pos, fixed_service)
#   cli =(group_pos, sub_pos)
_HTTP_HELPERS = {
    "_http_read_tool": ((2, 3, None, None), "GET"),
    "_http_write_tool": ((2, 3, None, None), "POST"),
    "_run_http": ((1, 2, 3, None), "GET"),
    "_call_zk": ((None, 2, 3, "coordinator-api"), "GET"),
    "_call_liquidity": ((None, 2, 3, "blockchain-rpc"), "GET"),
}
_CLI_HELPERS = {
    "_aitbc_cli_read_tool": (2, 3),
    "_run_aitbc_cli_write": (2, 3),
    "_run_aitbc_cli": (1, 2),
    "run_aitbc_command": (1, 2),
    "_build_aitbc_cli_command": (0, 1),
}


@dataclass
class ToolRow:
    tool: str
    file: str
    kind: str
    service: str = ""
    method: str = ""
    path: str = ""  # http path literal (template for f-strings)
    group: str = ""
    sub: tuple[str, ...] = ()  # cli subcommand tokens; empty = none/dynamic
    sub_dynamic: bool = False  # subcommand exists but is not a literal
    warnings: list[str] = field(default_factory=list)

    @property
    def literal(self) -> str:
        if self.kind == "rpc":
            return http_literal(self.service, self.path, self.method)
        if self.kind in ("cli", "generated"):
            toks = [self.group] if self.group else []
            toks += self.sub
            if self.sub_dynamic:
                toks.append("<dynamic>")
            return "aitbc " + " ".join(toks) if toks else "aitbc <dynamic>"
        return "—"


def http_literal(service: str, path: str, method: str = "") -> str:
    """Inventory display form for an HTTP dispatch literal."""
    if not path:
        return f"{service}:<dynamic>" if service else "—"
    if service == "blockchain-rpc":
        disp = "/rpc/" + path.lstrip("/")
    else:
        disp = f"{service}:{path}" if service else path
    return f"{method} {disp}".strip() if method else disp


# ---------------------------------------------------------------------------
# AST literal extraction
# ---------------------------------------------------------------------------


def _str_lit(node: ast.AST) -> str | None:
    """String literal or f-string template (``{expr}`` placeholders), else None."""
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value
    if isinstance(node, ast.JoinedStr):
        parts: list[str] = []
        for v in node.values:
            if isinstance(v, ast.Constant):
                parts.append(str(v.value))
            elif isinstance(v, ast.FormattedValue):
                parts.append("{" + ast.unparse(v.value) + "}")
            else:
                return None
        return "".join(parts)
    return None


def _sub_lit(node: ast.AST | None) -> tuple[tuple[str, ...], bool]:
    """Subcommand arg -> (tokens, dynamic). String, list of strings, or None."""
    if node is None:
        return (), False
    if isinstance(node, ast.Constant) and node.value is None:
        return (), False
    s = _str_lit(node)
    if s is not None:
        return tuple(t for t in s.split() if t), False
    if isinstance(node, (ast.List, ast.Tuple)):
        toks: list[str] = []
        for elt in node.elts:
            s = _str_lit(elt)
            if s is None:
                return (), True
            toks.append(s)
        return tuple(toks), False
    return (), True


def _arg(call: ast.Call, pos: int, kw: str) -> ast.AST | None:
    """Positional-or-keyword argument of a call."""
    for k in call.keywords:
        if k.arg == kw:
            return k.value
    return call.args[pos] if pos < len(call.args) else None


def _helper_name(call: ast.Call) -> str:
    f = call.func
    if isinstance(f, ast.Name):
        return f.id
    if isinstance(f, ast.Attribute):
        return f.attr
    return ""


def _apply_http(row: ToolRow, call: ast.Call, spec: tuple, default_method: str) -> None:
    svc_pos, path_pos, method_pos, fixed_svc = spec
    svc = fixed_svc or _str_lit(_arg(call, svc_pos, "service") or ast.Constant(value=""))
    path_node = _arg(call, path_pos, "path")
    path = _str_lit(path_node) if path_node is not None else None
    method = default_method
    if method_pos is not None:
        m = _str_lit(_arg(call, method_pos, "method") or ast.Constant(value=""))
        if m:
            method = m.upper()
    row.kind = "rpc"
    row.service = svc or ""
    row.method = method
    row.path = path or ""
    if path_node is not None and path is None:
        row.warnings.append("non-literal path")


def _apply_cli(row: ToolRow, call: ast.Call, spec: tuple[int, int]) -> None:
    group_pos, sub_pos = spec
    group = _str_lit(_arg(call, group_pos, "group") or ast.Constant(value=""))
    sub, dynamic = _sub_lit(_arg(call, sub_pos, "subcommand"))
    row.kind = "cli"
    row.group = group or ""
    row.sub = sub
    row.sub_dynamic = dynamic
    if not group:
        row.warnings.append("non-literal group")


def _classify_call(row: ToolRow, call: ast.Call) -> bool:
    """Fill `row` from a dispatch-helper call. True when recognized."""
    name = _helper_name(call)
    if name in _HTTP_HELPERS:
        spec, default_method = _HTTP_HELPERS[name]
        _apply_http(row, call, spec, default_method)
        return True
    if name in _CLI_HELPERS:
        _apply_cli(row, call, _CLI_HELPERS[name])
        return True
    return False


def _is_tool(func: ast.AST) -> bool:
    for dec in getattr(func, "decorator_list", []):
        if isinstance(dec, ast.Call):
            dec = dec.func
        if isinstance(dec, ast.Attribute) and dec.attr == "tool":
            return True
        if isinstance(dec, ast.Name) and dec.id == "tool":
            return True
    return False


def _tool_row(py: Path, func: ast.FunctionDef | ast.AsyncFunctionDef) -> ToolRow:
    generated = py.name.startswith(GENERATED_PREFIX)
    row = ToolRow(tool=func.name, file=f"mcp-server/{py.name}", kind="other")
    for node in ast.walk(func):
        if isinstance(node, ast.Call) and _classify_call(row, node):
            break
    if generated and row.kind in ("cli", "other"):
        row.kind = "generated"
    return row


def iter_tool_rows() -> list[ToolRow]:
    """One ToolRow per @mcp.tool function across mcp-server/, sorted."""
    rows: list[ToolRow] = []
    for py in sorted(MCP_DIR.glob("*.py")):
        tree = ast.parse(py.read_text(), filename=str(py))
        for node in tree.body:
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and _is_tool(node):
                rows.append(_tool_row(py, node))
    rows.sort(key=lambda r: (r.file, r.tool))
    return rows


# ---------------------------------------------------------------------------
# Markdown emission
# ---------------------------------------------------------------------------


def _cell(text: str) -> str:
    return text.replace("|", "\\|") if text else "—"


def _summary_lines(rows: list[ToolRow]) -> list[str]:
    by_kind: dict[str, int] = {}
    by_file: dict[str, int] = {}
    for r in rows:
        by_kind[r.kind] = by_kind.get(r.kind, 0) + 1
        by_file[r.file] = by_file.get(r.file, 0) + 1
    out = [f"**{len(rows)} tools** across {len(by_file)} modules.", ""]
    out.append("| Kind | Tools |")
    out.append("|---|---|")
    for kind in sorted(by_kind):
        out.append(f"| {kind} | {by_kind[kind]} |")
    out.append("")
    out.append("| File | Tools |")
    out.append("|---|---|")
    for f in sorted(by_file):
        out.append(f"| {f} | {by_file[f]} |")
    return out


def render(rows: list[ToolRow]) -> str:
    lines = [MARKER, "", "# MCP tool inventory", ""]
    lines += _summary_lines(rows)
    lines += [
        "",
        "| Tool | File | Kind | Route or command |",
        "|---|---|---|---|",
    ]
    for r in rows:
        lines.append(f"| `{r.tool}` | {_cell(r.file)} | {r.kind} | `{_cell(r.literal)}` |")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="exit 1 if the doc is stale")
    args = ap.parse_args(argv)

    text = render(iter_tool_rows())
    if args.check:
        if not OUT.exists():
            print(f"Missing {OUT.relative_to(REPO)} — run scripts/dev/gen_mcp_tool_inventory.py", file=sys.stderr)
            return 1
        if OUT.read_text() != text:
            print(f"Stale {OUT.relative_to(REPO)} — run scripts/dev/gen_mcp_tool_inventory.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
