#!/usr/bin/env python3
"""Generate one reference page per `aitbc` command under docs/cli/commands/.

Walks the live Click tree (same entry point as scripts/generate_cli_docs.py —
lazy proxies in cli/aitbc_cli/core/main.py are resolved, never invoked) and
emits a flat directory of pages named ``<group>-<command>.md`` (deeper paths
join with more hyphens: ``market escrow refund`` -> ``market-escrow-refund.md``)
plus a grouped ``README.md`` index.

Cross-links come from the mesh index
``docs/reference/feature-scenario-record-mesh.md``: every ``aitbc ...`` path
listed in Table A / Table B that is a token-prefix of the command path
contributes its record types, scenarios and feature docs to the page's
"Related" section. Links are re-based relative to docs/cli/commands/ and only
emitted when the target file exists.

Completely disjoint from scripts/generate_cli_docs.py (which owns
cli/README.md, cli/CLI_USAGE_GUIDE.md and cli/man/aitbc.1): this generator
only writes files under docs/cli/commands/ that carry its own marker.

Usage:
    python3 scripts/docs/gen_cli_command_docs.py           # rewrite pages
    python3 scripts/docs/gen_cli_command_docs.py --check   # exit 1 if out of date
"""

from __future__ import annotations

import argparse
import os
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

# Match the sys.path dance in cli_gap_analysis.py so the repo-root aitbc package
# wins over any installed packages/py .pth entries (repo root first, cli/ for
# aitbc_cli — required on worktrees where the editable install points at the
# primary checkout).
os.environ.setdefault("AITBC_SKIP_ENV_FILES", "1")

REPO = Path(__file__).resolve().parents[2]
_cli_src = str(REPO / "cli")
if _cli_src in sys.path:
    sys.path.remove(_cli_src)
sys.path.insert(0, _cli_src)
_repo = str(REPO)
if _repo in sys.path:
    sys.path.remove(_repo)
sys.path.insert(0, _repo)

import click  # noqa: E402

from cli_gap_analysis import cli  # noqa: E402

OUT_DIR = REPO / "docs" / "cli" / "commands"
MESH = REPO / "docs" / "reference" / "feature-scenario-record-mesh.md"
MARKER = "<!-- generated by scripts/docs/gen_cli_command_docs.py — do not edit -->"

DEFAULT_RPC_URL = "http://127.0.0.1:8202/rpc"


# ---------------------------------------------------------------------------
# CLI tree walking
# ---------------------------------------------------------------------------


def iter_commands() -> list[tuple[tuple[str, ...], click.Command]]:
    """Return [(path tokens, leaf command)] for every runnable command."""
    out: list[tuple[tuple[str, ...], click.Command]] = []

    def walk(cmd: click.Command, path: tuple[str, ...]) -> None:
        if isinstance(cmd, click.Group):
            for name in sorted(cmd.commands):
                walk(cmd.commands[name], path + (name,))
        else:
            out.append((path, cmd))

    for top in sorted(cli.commands):
        walk(cli.commands[top], (top,))
    return out


def page_name(path: tuple[str, ...]) -> str:
    return "-".join(path) + ".md"


# ---------------------------------------------------------------------------
# Mesh index parsing (record types / scenarios / features per CLI path)
# ---------------------------------------------------------------------------


@dataclass
class MeshEntry:
    records: set[str] = field(default_factory=set)
    scenarios: dict[str, str] = field(default_factory=dict)  # text -> file
    features: dict[str, str] = field(default_factory=dict)


_CODE = re.compile(r"`([^`]+)`")
_LINK = re.compile(r"\[([^\]]*)\]\(([^)]+)\)")

V9_POLICY = REPO / "apps" / "blockchain-node" / "src" / "aitbc_chain" / "state" / "v9_policy.py"


def _known_record_types() -> set[str]:
    """The authoritative record-type set: V9_METRIC_KNOWN_TX_TYPES parsed out of
    v9_policy.py. Mesh cells use ``ESCROW_LOCK``/``RELEASE``/``REFUND``-style
    shorthand; only full type names from this set are kept."""
    try:
        text = V9_POLICY.read_text()
    except OSError:
        return set()
    m = re.search(r"V9_METRIC_KNOWN_TX_TYPES\s*=\s*frozenset\(\s*\{([^}]*)\}", text)
    if not m:
        return set()
    return set(re.findall(r'"([A-Z0-9_]+)"', m.group(1)))


def _cli_tokens(span: str) -> tuple[str, ...] | None:
    toks = span.strip().split()
    if toks and toks[0] == "aitbc":
        toks = toks[1:]
    if not toks or not all(re.fullmatch(r"[a-z0-9][a-z0-9_-]*", t) for t in toks):
        return None
    return tuple(toks)


def _targets(cell: str, subdir: str) -> dict[str, str]:
    """{display: filename} for links into docs/<subdir>/ from the mesh doc."""
    out: dict[str, str] = {}
    for text, href in _LINK.findall(cell):
        if f"/{subdir}/" not in href:
            continue
        fname = href.split("/")[-1]
        if not fname.endswith(".md"):
            continue
        if not (REPO / "docs" / subdir / fname).exists():
            continue
        label = text.strip() or fname.removesuffix(".md")
        out[label] = fname
    return out


def load_mesh() -> dict[tuple[str, ...], MeshEntry]:
    """Parse Table A and Table B of the mesh index into CLI-path -> links."""
    entries: dict[tuple[str, ...], MeshEntry] = {}
    known_types = _known_record_types()
    table = None
    for line in MESH.read_text().splitlines():
        if line.startswith("## Table A"):
            table = "A"
            continue
        if line.startswith("## Table B"):
            table = "B"
            continue
        if line.startswith("## "):
            table = None
            continue
        if table is None or not line.strip().startswith("|"):
            continue
        _mesh_row(table, line, known_types, entries)
    return entries


def _mesh_row(table: str, line: str, known_types: set[str], entries: dict[tuple[str, ...], MeshEntry]) -> None:
    cells = [c.strip() for c in line.strip().strip("|").split("|")]
    if len(cells) < 4 or cells[0].startswith("---") or cells[0].lower() in ("record type", "feature doc"):
        return
    if table == "A":
        record_cell, cli_cell, scen_cell, feat_cell = cells[0], cells[1], cells[2], cells[3]
    else:  # Table B: feature | records | scenarios | cli
        feat_cell, record_cell, scen_cell, cli_cell = cells[0], cells[1], cells[2], cells[3]
    if cli_cell.lower().startswith("protocol-internal"):
        return
    records = {s for s in _CODE.findall(record_cell) if s in known_types}
    scenarios = _targets(scen_cell, "scenarios")
    features = _targets(feat_cell, "features")
    for span in _CODE.findall(cli_cell):
        toks = _cli_tokens(span)
        if toks is None:
            continue
        e = entries.setdefault(toks, MeshEntry())
        e.records |= records
        e.scenarios |= scenarios
        e.features |= features
        if table == "B":
            e.features |= _targets(feat_cell, "features")


def mesh_for(path: tuple[str, ...], mesh: dict[tuple[str, ...], MeshEntry]) -> MeshEntry:
    """Union every mesh entry whose CLI path is a token-prefix of `path`."""
    out = MeshEntry()
    for toks, e in mesh.items():
        if path[: len(toks)] == toks:
            out.records |= e.records
            out.scenarios |= e.scenarios
            out.features |= e.features
    return out


# ---------------------------------------------------------------------------
# Rendering
# ---------------------------------------------------------------------------


def _default_str(p: click.Parameter) -> str:
    d = p.default
    if d is None or str(type(d)).endswith("Sentinel'>") or repr(d) == "Sentinel.UNSET":
        return "—"
    if callable(d):
        return "—"
    if isinstance(d, bool):
        return "`true`" if d else "`false`"
    s = str(d)
    return f"`{s}`" if s else "—"


def _help_str(p: click.Parameter) -> str:
    h = (getattr(p, "help", None) or "").strip()
    return " ".join(h.split()) or "—"


def options_table(cmd: click.Command) -> list[str]:
    opts = [p for p in cmd.params if isinstance(p, click.Option)]
    if not opts:
        return []
    lines = ["## Options", "", "| Option | Type | Default | Required | Description |", "|---|---|---|---|---|"]
    for p in opts:
        flags = ", ".join(f"`{o}`" for o in list(p.opts) + list(p.secondary_opts))
        typ = p.type.name
        if getattr(p, "multiple", False):
            typ += " (multiple)"
        if getattr(p, "is_flag", False):
            typ = "flag"
        desc = _help_str(p)
        if re.search(r":\d{4}\b", str(p.default)):
            # A `host:port` default (e.g. --rpc-url) gets attributed to the
            # nearest service name in preceding rows; mark it intentionally.
            desc += " <!-- check-ports: ignore -->"
        lines.append(f"| {flags} | {typ} | {_default_str(p)} | {'yes' if p.required else 'no'} | {desc} |")
    lines.append("")
    return lines


def arguments_table(cmd: click.Command) -> list[str]:
    args = [p for p in cmd.params if isinstance(p, click.Argument)]
    if not args:
        return []
    lines = ["## Arguments", "", "| Argument | Type | Required | Description |", "|---|---|---|---|"]
    for p in args:
        name = f"`{p.name}`"
        typ = p.type.name + (" …" if p.nargs == -1 else "")
        lines.append(f"| {name} | {typ} | {'yes' if p.required else 'no'} | {_help_str(p)} |")
    lines.append("")
    return lines


def usage_line(path: tuple[str, ...], cmd: click.Command) -> str:
    parts = ["aitbc", *path]
    if any(isinstance(p, click.Option) for p in cmd.params):
        parts.append("[OPTIONS]")
    for p in cmd.params:
        if not isinstance(p, click.Argument):
            continue
        mv = (p.metavar or p.name.upper()) if p.nargs != -1 else f"{(p.metavar or p.name.upper())}..."
        parts.append(mv if p.required else f"[{mv}]")
    return " ".join(parts)


def _help_examples(help_text: str) -> list[str]:
    """Pull `aitbc ...` lines out of an Examples: block in the command help."""
    lines = help_text.splitlines()
    out: list[str] = []
    for i, line in enumerate(lines):
        if not re.match(r"^\s*examples?\s*:?\s*$", line, re.IGNORECASE):
            continue
        for follow in lines[i + 1 :]:
            s = follow.strip()
            if not s:
                if out:
                    break
                continue
            s = s.lstrip("$# ").strip() if s.startswith(("$ ", "# ")) else s
            if s.startswith("aitbc "):
                out.append(s)
            elif out:
                break
            if len(out) >= 3:
                break
        break
    return out[:3]


def _minimal_invocation(path: tuple[str, ...], cmd: click.Command) -> str:
    base = "aitbc " + " ".join(path)
    req = [(p.metavar or p.name.upper()) for p in cmd.params if isinstance(p, click.Argument) and p.required and p.nargs != -1]
    req_opts = [
        f"{p.opts[0]} <{p.name}>"
        for p in cmd.params
        if isinstance(p, click.Option) and p.required and not getattr(p, "is_flag", False)
    ]
    return " ".join([base, *req_opts, *req])


def _synthetic_examples(path: tuple[str, ...], cmd: click.Command) -> list[str]:
    opts = [p for p in cmd.params if isinstance(p, click.Option)]
    minimal = _minimal_invocation(path, cmd)
    synthetic = [minimal]
    if any("--rpc-url" in p.opts for p in opts):
        # Env-assignment form: `RPC_URL=...:8202` self-attributes the port to the
        # blockchain RPC service for scripts/docs/check_ports.py, where a bare
        # `host:8202` later in the line would inherit the command's own name
        # (e.g. `wallet send` -> wallet daemon) and fail the audit.
        synthetic.append(f"RPC_URL={DEFAULT_RPC_URL}")
        synthetic.append(f'{minimal} --rpc-url "$RPC_URL"')
    if any("--output" in p.opts or "--json" in p.opts for p in opts):
        flag = "--output" if any("--output" in p.opts for p in opts) else "--json"
        synthetic.append(f"{minimal} {flag} json" if flag == "--output" else f"{minimal} {flag}")
    return synthetic


def examples(path: tuple[str, ...], cmd: click.Command) -> list[str]:
    found = _help_examples(cmd.help or "")
    out = found if found else _synthetic_examples(path, cmd)
    return out[:3]


def related_section(entry: MeshEntry) -> list[str]:
    if not (entry.records or entry.scenarios or entry.features):
        return []
    lines = ["## Related", ""]
    if entry.records:
        lines.append("- On-chain record types: " + ", ".join(f"`{r}`" for r in sorted(entry.records)))
    if entry.scenarios:
        links = ", ".join(f"[{t}](../../scenarios/{f})" for t, f in sorted(entry.scenarios.items()))
        lines.append(f"- Scenarios: {links}")
    if entry.features:
        links = ", ".join(f"[{t}](../../features/{f})" for t, f in sorted(entry.features.items()))
        lines.append(f"- Feature docs: {links}")
    lines.append("- [Feature ↔ scenario ↔ record mesh](../../reference/feature-scenario-record-mesh.md)")
    lines.append("")
    return lines


def render_page(path: tuple[str, ...], cmd: click.Command, mesh: dict[tuple[str, ...], MeshEntry]) -> str:
    lines = [MARKER, "", f"# `aitbc {' '.join(path)}`", ""]
    help_text = " ".join((cmd.help or "").split()) or "—"
    lines += [help_text, ""]
    lines += ["## Usage", "", "```bash", usage_line(path, cmd), "```", ""]
    lines += arguments_table(cmd)
    lines += options_table(cmd)
    ex = examples(path, cmd)
    lines += ["## Examples", "", "```bash", *ex, "```", ""]
    lines += related_section(mesh_for(path, mesh))
    return "\n".join(lines).rstrip() + "\n"


def render_index(leaves: list[tuple[tuple[str, ...], click.Command]], mesh: dict[tuple[str, ...], MeshEntry]) -> str:
    lines = [
        MARKER,
        "",
        "# `aitbc` command reference",
        "",
        "One generated page per `aitbc` command — usage, options, examples, and",
        "cross-links into the [feature ↔ scenario ↔ record mesh](../../reference/feature-scenario-record-mesh.md).",
        "Regenerate with `scripts/docs/gen_cli_command_docs.py`.",
        "",
    ]
    groups: dict[str, list[tuple[str, ...]]] = {}
    lookup = dict(leaves)
    for path, _cmd in leaves:
        groups.setdefault(path[0], []).append(path)
    for top in sorted(groups):
        lines.append(f"## `{top}`")
        lines.append("")
        for path in sorted(groups[top]):
            cmd = lookup[path]
            desc = " ".join((cmd.help or "").splitlines()[0].split()) if cmd.help else ""
            link = page_name(path)
            lines.append(f"- [`aitbc {' '.join(path)}`]({link})" + (f" — {desc}" if desc else ""))
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------


def generate() -> dict[str, str]:
    """Return {relative path: content} for every generated file."""
    leaves = iter_commands()
    mesh = load_mesh() if MESH.exists() else {}
    names: dict[str, tuple[str, ...]] = {}
    for path, _cmd in leaves:
        n = page_name(path)
        if n in names and names[n] != path:
            raise SystemExit(f"page-name collision: {names[n]} and {path} both map to {n}")
        names[n] = path
    out: dict[str, str] = {"README.md": render_index(leaves, mesh)}
    for path, cmd in leaves:
        out[page_name(path)] = render_page(path, cmd, mesh)
    return out


def main() -> int:
    parser = argparse.ArgumentParser(description="Regenerate per-command CLI docs")
    parser.add_argument("--check", action="store_true", help="Fail if docs would change")
    args = parser.parse_args()

    files = generate()
    if args.check:
        dirty = False
        for name, content in sorted(files.items()):
            p = OUT_DIR / name
            if not p.exists() or p.read_text() != content:
                print(f"Would change {p.relative_to(REPO)}")
                dirty = True
        stale = {p.name for p in OUT_DIR.glob("*.md")} - set(files) if OUT_DIR.exists() else set()
        for s in sorted(stale):
            print(f"Stale generated file: {(OUT_DIR / s).relative_to(REPO)}")
            dirty = True
        return 1 if dirty else 0

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for name, content in sorted(files.items()):
        (OUT_DIR / name).write_text(content)
    print(f"Wrote {len(files)} files to {OUT_DIR.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
