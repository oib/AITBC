def emit_record_hub(ctx: dict) -> str:
    lines = [
        MARKER,
        "",
        "# Record types",
        "",
        "One row per `V9_METRIC_KNOWN_TX_TYPES` record type — the full-mesh",
        "landing page joining the coverage ledger, CLI pages, scenarios,",
        "feature docs, RPC routes and waiver rows.",
        "",
        "| Record type | Sealed on bc-2 | CLI page(s) | Scenario(s) | Feature doc(s) | RPC route(s) | Waiver / decision | Source |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for t in ctx["known"]:
        idx = ctx["type_index"].get(t, {"cli": {}, "scenarios": {}, "features": {}})
        sealed = ctx["ledger"].get(t, {}).get("sealed", "—")
        cli = _links_cell(idx["cli"], "../cli/commands/")
        scen = _links_cell(idx["scenarios"], "../scenarios/")
        feat = _links_cell(idx["features"], "../features/")
        routes = _route_cell(ctx["routes_by_type"].get(t, set()))
        waiver = _waiver_cell(t, ctx)
        dead = " ☠ *(dead — replay-pinned)*" if t in ctx["dead"] else ""
        lines.append(
            f"| `{t}`{dead} | {sealed} | {cli} | {scen} | {feat} | {routes} | {waiver} | `V9_METRIC_KNOWN_TX_TYPES` |"
        )
    lines.append("")
    return "\n".join(lines)


def _route_cell(routes: set[str], cap: int = 8) -> str:
    if not routes:
        return "—"
    keys = sorted(routes)
    out = [f"`{k}`" for k in keys[:cap]]
    if len(keys) > cap:
        out.append(f"+{len(keys) - cap} more")
    return ", ".join(out)


def _waiver_cell(tx_type: str, ctx: dict) -> str:
    parts: list[str] = []
    if tx_type in ctx["waivers"]:
        parts.append(f"[{ctx['waivers'][tx_type]}](../decisions/v1-v9-live-exercise-waivers.md)")
    for ref in sorted(ctx["decisions"].get(tx_type, ())):
        parts.append(f"[{ref}](../decisions/README.md)")
    return ", ".join(parts) if parts else "—"


def emit_route_map(ctx: dict) -> str:
    lines = [
        MARKER,
        "",
        "# CLI ↔ RPC route map",
        "",
        "Every `/rpc/...` literal called from `cli/aitbc_cli`, attributed to its",
        "`aitbc` command path (via the same-file call graph) and to the",
        "server-side owner function in `aitbc_chain/rpc/`. Route→type",
        "association is keyword-based best-effort; `—` means unmatched.",
        "",
        "| `aitbc` command | Route literal | Owner function | Record type(s) |",
        "|---|---|---|---|",
    ]
    rows: list[tuple[str, str, str, str]] = []
    for cmd_path, literals in ctx["cli_calls"].items():
        for lit in sorted(literals):
            r = match_route(lit, ctx["routes"])
            owner = f"`{r.func}` ({r.file.split('/')[-1]})" if r else "—"
            types = ", ".join(f"`{t}`" for t in sorted(r.types)) if r and r.types else "—"
            rows.append(("aitbc " + " ".join(cmd_path), f"`{lit}`", owner, types))
    for file, literals in ctx["cli_loose"].items():
        for lit in sorted(literals):
            rows.append((f"*(unattributed — {file})*", f"`{lit}`", "—", "—"))
    for cmd, lit, owner, types in sorted(rows):
        lines.append(
            f"| `{cmd}` | {lit} | {owner} | {types}" if not cmd.startswith("*") else f"| {cmd} | {lit} | {owner} | {types}"
        )
    lines.append("")
    return "\n".join(lines)


def emit_test_map(ctx: dict) -> str:
    lines = [
        MARKER,
        "",
        "# Record-type test map",
        "",
        "Inverted index: each `V9_METRIC_KNOWN_TX_TYPES` record type → the",
        "`tests/` files that name it as a quoted literal.",
        "",
        "| Record type | Test files |",
        "|---|---|",
    ]
    for t in ctx["known"]:
        files = sorted(ctx["tests"].get(t, ()))
        if files:
            cell = ", ".join(f"[{f.split('/')[-1]}](../../{f})" for f in files)
        else:
            cell = "—"
        lines.append(f"| `{t}` | {cell} |")
    lines.append("")
    return "\n".join(lines)


def build_context() -> dict:
    known_list = _known_types()
    known = set(known_list)
    routes = parse_routes(known)
    cli_calls, cli_loose = parse_cli_calls()
    routes_by_type: dict[str, set[str]] = {}
    for r in routes:
        for t in r.types:
            routes_by_type.setdefault(t, set()).add(r.path)
    return {
        "known": known_list,
        "dead": _dead_types(),
        "ledger": parse_ledger(known),
        "waivers": parse_waivers(known),
        "decisions": parse_decisions(known),
        "routes": routes,
        "routes_by_type": routes_by_type,
        "cli_calls": cli_calls,
        "cli_loose": cli_loose,
        "tests": parse_tests(known),
        "type_index": _type_indexes(known_list),
    }


def generate(ctx: dict) -> dict[str, str]:
    return {
        "docs/reference/record-types.md": emit_record_hub(ctx),
        "docs/reference/cli-rpc-route-map.md": emit_route_map(ctx),
        "docs/testing/record-type-test-map.md": emit_test_map(ctx),
    }


def _check(files: dict[str, str]) -> int:
    dirty = False
    for rel, content in sorted(files.items()):
        p = REPO / rel
        if not p.exists() or p.read_text() != content:
            print(f"Would change {rel}")
            dirty = True
    for md in DOCS.rglob("*.md"):
        rel = md.relative_to(REPO).as_posix()
        if rel in files:
            continue
        try:
            head = md.read_text()[:300]
        except OSError:
            continue
        if MARKER in head:
            print(f"Stale generated file: {rel}")
            dirty = True
    return 1 if dirty else 0


def main() -> int:
    parser = argparse.ArgumentParser(description="Regenerate doc-mesh cross-index docs")
    parser.add_argument("--check", action="store_true", help="Fail if docs would change")
    args = parser.parse_args()
    files = generate(build_context())
    if args.check:
        return _check(files)
    for rel, content in sorted(files.items()):
        p = REPO / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(content)
        print(f"Wrote {rel}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
