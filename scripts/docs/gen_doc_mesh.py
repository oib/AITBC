def parse_tests(known: set[str]) -> dict[str, set[str]]:
    """{record type: {tests/...py}} — quoted type literals anywhere in tests/."""
    pat = re.compile(r"['\"]([A-Z0-9_]{3,})['\"]")
    out: dict[str, set[str]] = {}
    for py in sorted((REPO / "tests").rglob("*.py")):
        found = {t for t in pat.findall(py.read_text()) if t in known}
        rel = py.relative_to(REPO).as_posix()
        for t in found:
            out.setdefault(t, set()).add(rel)
    return out


def _type_indexes(known: set[str]) -> dict[str, dict[str, dict[str, str]]]:
    """{type: {'cli': {page: path}, 'scenarios': {label: file}, 'features': {label: file}}}."""
    mesh = gcd.load_mesh()
    leaves = gcd.iter_commands()
    out: dict[str, dict[str, dict[str, str]]] = {t: {"cli": {}, "scenarios": {}, "features": {}} for t in known}
    for path, _cmd in leaves:
        entry = gcd.mesh_for(path, mesh)
        for t in entry.records & set(known):
            out[t]["cli"]["aitbc " + " ".join(path)] = gcd.page_name(path)
            out[t]["scenarios"].update(entry.scenarios)
            out[t]["features"].update(entry.features)
    return out


def _links_cell(items: dict[str, str], prefix: str, cap: int = 8) -> str:
    if not items:
        return "—"
    keys = sorted(items)
    links = [f"[{k}]({prefix}{items[k]})" for k in keys[:cap]]
    if len(keys) > cap:
        links.append(f"+{len(keys) - cap} more")
    return ", ".join(links)


