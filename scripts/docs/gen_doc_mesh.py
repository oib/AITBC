#!/usr/bin/env python3
"""Generate the doc-mesh cross-index artifacts under docs/.

Four generated documents, all derived from mechanical source data:

- ``docs/reference/record-types.md`` — one row per
  ``V9_METRIC_KNOWN_TX_TYPES`` record type: live-seal evidence from the
  coverage ledger in ``docs/scenarios/README.md``, CLI pages, scenarios and
  feature docs from the mesh index, matching RPC routes, waiver rows, and
  the source anchor.
- ``docs/reference/cli-rpc-route-map.md`` — every ``/rpc/...`` literal
  called from ``cli/aitbc_cli``, attributed to its `aitbc` command path,
  the server-side owner function, and associated record types (keyword
  association — best-effort, ``—`` when unmatched).
- ``docs/testing/record-type-test-map.md`` — inverted index of record-type
  literals found in ``tests/``.

Route and command attribution is deliberately honest: dynamic route
construction and calls that cannot be tied to a Click command are listed
as unattributed rather than guessed.

Usage:
    python3 scripts/docs/gen_doc_mesh.py           # rewrite the four docs
    python3 scripts/docs/gen_doc_mesh.py --check   # exit 1 if out of date
"""

from __future__ import annotations

import argparse
import ast
import os
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

os.environ.setdefault("AITBC_SKIP_ENV_FILES", "1")

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "scripts" / "docs"))

import gen_cli_command_docs as gcd  # noqa: E402

DOCS = REPO / "docs"
MARKER = "<!-- generated by scripts/docs/gen_doc_mesh.py — do not edit -->"

OUT_FILES = {
    "docs/reference/record-types.md": "record-types",
    "docs/reference/cli-rpc-route-map.md": "route-map",
    "docs/testing/record-type-test-map.md": "test-map",
}

_CODE = re.compile(r"`([^`]+)`")
_LINK = re.compile(r"\[([^\]]*)\]\(([^)]+)\)")

# ---------------------------------------------------------------------------
# Source parsing: ledger, waivers, decisions
# ---------------------------------------------------------------------------


def _table_rows(path: Path, start_heading: str) -> list[list[str]]:
    """Rows of the first markdown table following `start_heading`."""
    rows: list[list[str]] = []
    in_table = False
    for line in path.read_text().splitlines():
        if line.startswith("#"):
            if in_table:
                break
            in_table = line.startswith(start_heading)
            continue
        if not in_table:
            continue
        if not line.strip().startswith("|"):
            if rows:
                break
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if cells and cells[0].startswith("---"):
            continue
        rows.append(cells)
    return rows


def _known_types() -> list[str]:
    return sorted(gcd._known_record_types())


def _dead_types() -> set[str]:
    """Record types that are dead by design (replay-pinned only).

    Parsed from ``DEAD_RECORD_TYPES`` in ``v9_policy.py`` — the module has
    relative imports and cannot be exec'd standalone, so read the literal
    set via AST instead.
    """
    tree = ast.parse((REPO / "apps/blockchain-node/src/aitbc_chain/state/v9_policy.py").read_text())
    for node in tree.body:
        if isinstance(node, ast.Assign) and getattr(node.targets[0], "id", "") == "DEAD_RECORD_TYPES":
            return {elt.value for elt in ast.walk(node.value) if isinstance(elt, ast.Constant) and isinstance(elt.value, str)}
    return set()


def parse_ledger(known: set[str]) -> dict[str, dict[str, str]]:
    """docs/scenarios/README.md coverage ledger -> {type: {sealed, emitted}}."""
    rows = _table_rows(DOCS / "scenarios" / "README.md", "## On-chain record coverage")
    out: dict[str, dict[str, str]] = {}
    for cells in rows:
        if len(cells) < 4 or "Record type" in cells[0]:
            continue
        types = [t for t in _CODE.findall(cells[0]) if t in known]
        if not types:
            continue
        sealed_cell = cells[3]
        for t in types:
            out[t] = {"sealed": _sealed_for(t, sealed_cell, len(types)), "emitted": cells[1]}
    return out


def _sealed_for(tx_type: str, cell: str, n_types: int) -> str:
    """Pick the per-type segment out of a shared 'sealed on bc-2' cell."""
    if n_types == 1:
        return cell or "—"
    suffix = tx_type.rsplit("_", 1)[-1]
    for seg in cell.split(";"):
        seg = seg.strip()
        if seg.upper().startswith(suffix):
            return seg[len(suffix) :].strip() or seg
    return cell or "—"


def parse_waivers(known: set[str]) -> dict[str, str]:
    """docs/decisions/v1-v9-live-exercise-waivers.md type rows -> {type: 'V-1'}."""
    rows = _table_rows(DOCS / "decisions" / "v1-v9-live-exercise-waivers.md", "## The 22 waived types")
    out: dict[str, str] = {}
    for cells in rows:
        t = cells[0].strip("` ")
        if t in known:
            out[t] = "V-1"
    return out


def parse_decisions(known: set[str]) -> dict[str, set[str]]:
    """docs/decisions/README.md card rows -> {type: {ref}} for rows that name a type."""
    rows = _table_rows(DOCS / "decisions" / "README.md", "# Decision log")
    out: dict[str, set[str]] = {}
    for cells in rows:
        if len(cells) < 3:
            continue
        ref = cells[1].strip("` ")
        if not ref or ref == "Ref":
            continue
        for t in _CODE.findall(" ".join(cells[2:])):
            t = t.strip()
            if t in known:
                out.setdefault(t, set()).add(ref)
    return out


# ---------------------------------------------------------------------------
# Source parsing: RPC routes (server side)
# ---------------------------------------------------------------------------


@dataclass
class Route:
    method: str
    path: str  # full path including the /rpc mount point
    func: str
    file: str  # repo-relative
    types: set[str] = field(default_factory=set)


_ROUTE_DEC = re.compile(r'@router\.(get|post|put|delete|patch|websocket)\(\s*"([^"]*)"')
_PREFIX = re.compile(r'APIRouter\(\s*prefix="([^"]*)"')
_FUNC = re.compile(r"(?:async\s+)?def\s+(\w+)")


def parse_routes(known: set[str]) -> list[Route]:
    """Walk apps/blockchain-node/src/aitbc_chain/rpc/**/*.py for route literals."""
    rpc_dir = REPO / "apps" / "blockchain-node" / "src" / "aitbc_chain" / "rpc"
    routes: list[Route] = []
    for py in sorted(rpc_dir.rglob("*.py")):
        text = py.read_text()
        m = _PREFIX.search(text)
        prefix = m.group(1) if m else ""
        for dec in _ROUTE_DEC.finditer(text):
            method, path = dec.group(1), dec.group(2)
            fm = _FUNC.search(text, dec.end())
            func = fm.group(1) if fm else "?"
            body = text[fm.end() :] if fm else ""
            body = body[: _next_boundary(body)]
            rel = py.relative_to(REPO).as_posix()
            r = Route(method.upper(), "/rpc" + prefix + path, func, rel)
            r.types = _route_types(r, body, known)
            routes.append(r)
    routes.sort(key=lambda r: (r.path, r.method))
    return routes


def _next_boundary(body: str) -> int:
    """End of a handler body: next decorator or top-level def, else ~4k chars."""
    m = re.search(r"\n(@|async def |def )", body)
    return m.start() if m else min(len(body), 4000)


def _route_types(route: Route, body: str, known: set[str]) -> set[str]:
    """Type literals in the handler body, else keyword match on path tokens."""
    found = {t for t in re.findall(r'"([A-Z0-9_]{3,})"', body) if t in known}
    if found:
        return found
    tokens = set(re.split(r"[/{}_-]+", route.path.lower())) - {""}
    return {t for t in known if all(p.lower() in tokens for p in t.split("_"))}


def match_route(literal: str, routes: list[Route]) -> Route | None:
    """Match a CLI-side literal like /rpc/account/{canonical} to a server route."""
    lit_segs = [s for s in literal.split("/") if s]
    best: Route | None = None
    for r in routes:
        srv_segs = [s for s in r.path.split("/") if s]
        if len(srv_segs) != len(lit_segs):
            continue
        ok = all(a == b or (a.startswith("{") and b.startswith("{")) for a, b in zip(srv_segs, lit_segs, strict=True))
        if ok and best is None:
            best = r
    return best


# ---------------------------------------------------------------------------
# Source parsing: CLI /rpc/ call literals (ast)
# ---------------------------------------------------------------------------


def _route_literals(node: ast.AST, src: str) -> set[str]:
    out: set[str] = set()
    for sub in ast.walk(node):
        if isinstance(sub, ast.Constant) and isinstance(sub.value, str) and "/rpc/" in sub.value:
            lit = sub.value
            start = lit.find("/rpc/")
            out.add(re.sub(r"\s.*$", "", lit[start:]))
        elif isinstance(sub, ast.JoinedStr):
            lit = _joined(sub, src)
            if lit and "/rpc/" in lit:
                out.add(lit[lit.find("/rpc/") :])
    return {lit for lit in out if re.fullmatch(r"/rpc/[a-zA-Z0-9_{][\w/.{}-]*", lit)}


def _joined(node: ast.JoinedStr, src: str) -> str:
    parts: list[str] = []
    for v in node.values:
        if isinstance(v, ast.Constant):
            parts.append(str(v.value))
        elif isinstance(v, ast.FormattedValue):
            seg = ast.get_source_segment(src, v.value)
            parts.append("{" + (seg or "") + "}")
    return "".join(parts)


def _called_names(node: ast.AST) -> set[str]:
    names: set[str] = set()
    for sub in ast.walk(node):
        if isinstance(sub, ast.Call):
            f = sub.func
            if isinstance(f, ast.Name):
                names.add(f.id)
            elif isinstance(f, ast.Attribute):
                names.add(f.attr)
    return names


def _scan_cli_file(py: Path) -> tuple[dict[str, set[str]], dict[str, set[str]]]:
    """Return (func -> route literals, caller -> callee names) for one file."""
    src = py.read_text()
    try:
        tree = ast.parse(src)
    except SyntaxError:
        return {}, {}
    routes: dict[str, set[str]] = {}
    calls: dict[str, set[str]] = {}
    for node in ast.walk(tree):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            routes.setdefault(node.name, set()).update(_route_literals(node, src))
            calls.setdefault(node.name, set()).update(_called_names(node))
    return routes, calls


def _callback_map() -> dict[tuple[str, str], tuple[str, ...]]:
    """{(cli module name, function name): command path} from the Click tree."""
    out: dict[tuple[str, str], tuple[str, ...]] = {}
    for path, cmd in gcd.iter_commands():
        cb = getattr(cmd, "callback", None)
        if cb is None:
            continue
        out[(getattr(cb, "__module__", ""), getattr(cb, "__name__", ""))] = path
    return out


def parse_cli_calls() -> tuple[dict[tuple[str, ...], set[str]], dict[str, set[str]]]:
    """{command path: {/rpc literals}} plus {file: {literals}} unattributed."""
    cb_map = _callback_map()
    by_cmd: dict[tuple[str, ...], set[str]] = {}
    loose: dict[str, set[str]] = {}
    for py in sorted((REPO / "cli" / "aitbc_cli").rglob("*.py")):
        module = py.relative_to(REPO / "cli").with_suffix("").as_posix().replace("/", ".")
        module = module.removesuffix(".__init__")
        func_routes, calls = _scan_cli_file(py)
        callers = _reverse_callers(calls)
        rel = py.relative_to(REPO).as_posix()
        for func, literals in func_routes.items():
            if not literals:
                continue
            cmd_path = _resolve_cmd(module, func, callers, cb_map)
            if cmd_path:
                by_cmd.setdefault(cmd_path, set()).update(literals)
            else:
                loose.setdefault(rel, set()).update(literals)
    return by_cmd, loose


def _reverse_callers(calls: dict[str, set[str]]) -> dict[str, set[str]]:
    rev: dict[str, set[str]] = {}
    for caller, callees in calls.items():
        for c in callees:
            rev.setdefault(c, set()).add(caller)
    return rev


def _resolve_cmd(
    module: str, func: str, callers: dict[str, set[str]], cb_map: dict[tuple[str, str], tuple[str, ...]]
) -> tuple[str, ...] | None:
    """Walk up the same-file call graph until a Click callback is reached."""
    seen: set[str] = set()
    queue = [func]
    while queue:
        name = queue.pop(0)
        if name in seen:
            continue
        seen.add(name)
        hit = cb_map.get((module, name))
        if hit is not None:
            return hit
        queue.extend(sorted(callers.get(name, ())))
    return None


