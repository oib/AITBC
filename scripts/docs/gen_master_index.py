#!/usr/bin/env python3
"""Regenerate docs/MASTER_INDEX.md from the current docs/ tree.

MASTER_INDEX.md claims to be auto-generated but had no generator, so it drifted:
by 2026-09-11 it listed five directories that no longer existed, omitted two that
did, and every per-directory file count was wrong. This script is that generator.

Directory descriptions are hand-written and preserved in DESCRIPTIONS below; a new
directory with no entry is listed with an empty description for someone to fill in.

Usage:
    python3 scripts/docs/gen_master_index.py           # rewrite MASTER_INDEX.md
    python3 scripts/docs/gen_master_index.py --check   # exit 1 if out of date
"""

import sys
from datetime import date
from pathlib import Path

DESCRIPTIONS = {
    "agent": "Single agent integration and coordination",
    "agent-coordinator": "Agent coordinator service and API docs",
    "agent-sdk": "Agent SDK and communication guide",
    "api": "API integration, usage docs, and generated OpenAPI specs",
    "apps": "Application catalog and per-app landing pages",
    "architecture": "System architecture and design patterns",
    "archive": "Historical documents and archive",
    "audit": "Documentation audit and refresh status",
    "blockchain": "Blockchain node, consensus, networking",
    "ci-cd": "CI/CD pipeline and operations",
    "cli": "Command-line interface reference",
    "contracts": "Smart contract and ZK verification docs",
    "database": "Database schema, RLS, and migration docs",
    "deployment": "Deployment and infrastructure setup",
    "design": "Design documents and decisions",
    "development": "Developer guides and workflow",
    "features": "Feature specifications and deep dives",
    "getting-started": "New-user onboarding and setup",
    "governance": "Governance and voting documentation",
    "infrastructure": "Infrastructure and migration docs",
    "LIVE_VALIDATION_DAYS": "Per-day live validation logs for the public hub",
    "marketplace": "Marketplace, exchange, and trading docs",
    "meta": "Documentation standards, template, and compliance",
    "mining": "Mining operations and GPU provider docs",
    "ops": "Operational runbooks and key handling",
    "reference": "Quick lookup: ports, glossary, FAQ",
    "releases": "Release notes, changelogs, and status",
    "scenarios": "End-to-end usage scenarios",
    "security": "Security architecture and audits",
    "testing": "Test suite and validation documentation",
    "troubleshooting": "Troubleshooting guides",
    "ui": "User interface documentation",
    "web": "Website and rendered docs assets",
}

ENTRY_POINTS = [
    ("Documentation home", "README.md"),
    ("Getting started", "getting-started/README.md"),
    ("App catalog", "apps/README.md"),
    ("CLI README", "cli/README.md"),
    ("Service ports reference", "reference/SERVICE_PORTS.md"),
    ("Release status", "releases/STATUS.md"),
    ("Docs refresh audit", "audit/DOCS_REFRESH_AUDIT.md"),
]


def render(docs: Path) -> str:
    dirs = sorted((p for p in docs.iterdir() if p.is_dir()), key=lambda p: p.name.lower())
    root_files = sorted((p for p in docs.iterdir() if p.is_file()), key=lambda p: p.name.lower())
    total_md = sum(1 for _ in docs.rglob("*.md"))

    tree = ["docs/"] + [f"├── {d.name}/" for d in dirs] + [f"├── {f.name}" for f in root_files[:-1]]
    if root_files:
        tree.append(f"└── {root_files[-1].name}")

    rows = []
    for d in dirs:
        count = sum(1 for _ in d.rglob("*.md"))
        desc = DESCRIPTIONS.get(d.name, "")
        rows.append(f"| [{d.name}]({d.name}/) | {count} | {desc} |")

    lines = [
        "# AITBC Documentation Master Index",
        "",
        "**Complete catalog of all documentation files and directories**",
        "",
        f"**Last Updated**: {date.today().isoformat()}",
        "",
        "---",
        "",
        "## Directory structure",
        "",
        "```",
        *tree,
        "```",
        "",
        "## Directory stats",
        "",
        f"- **Top-level directories**: {len(dirs)}",
        f"- **Markdown files under docs/**: {total_md}",
        "",
        "| Directory | Files | Description |",
        "|---|---|---|",
        *rows,
        "",
        "## Key entry points",
        "",
        *[f"- [{label}]({t})" for label, t in ENTRY_POINTS if (docs / t).exists()],
        "",
        "---",
        "",
        "*Generated by `scripts/docs/gen_master_index.py`. Do not edit by hand —",
        "re-run the generator instead. Directory descriptions live in that script.*",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    docs = Path(__file__).resolve().parents[2] / "docs"
    target = docs / "MASTER_INDEX.md"
    content = render(docs)

    if "--check" in sys.argv:
        current = target.read_text() if target.exists() else ""
        # Ignore the date line so a stale-by-a-day stamp is not a CI failure.
        strip = lambda t: [l for l in t.splitlines() if not l.startswith("**Last Updated**")]
        if strip(current) != strip(content):
            print("MASTER_INDEX.md is out of date. Run: python3 scripts/docs/gen_master_index.py")
            return 1
        print("MASTER_INDEX.md is up to date.")
        return 0

    target.write_text(content)
    missing = [d.name for d in docs.iterdir() if d.is_dir() and d.name not in DESCRIPTIONS]
    print(f"Wrote {target}")
    if missing:
        print(f"NOTE: no description for: {', '.join(sorted(missing))}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
