#!/usr/bin/env bash
# install-nginx-node.sh
# Run this on any island node to expose AITBC services via nginx.
# Works for aitbc3, aitbc4, any future node — no manual editing required.
#
# Usage: sudo bash /opt/aitbc/scripts/setup/install-nginx-node.sh
set -euo pipefail

AITBC_DIR="$(cd "$(dirname "$0")/../.." && pwd)"
NGINX_CONF_SRC="$AITBC_DIR/examples/nginx/nginx-aitbc.conf.example"
# #1023: env overrides so the script can be rehearsed against a scratch
# tree — never overwrite /etc/nginx paths in a test.
NGINX_SITES_AVAILABLE="${NGINX_SITES_AVAILABLE:-/etc/nginx/sites-available/aitbc}"
NGINX_SITES_ENABLED="${NGINX_SITES_ENABLED:-/etc/nginx/sites-enabled/aitbc}"
NGINX_OVERRIDE="${NGINX_OVERRIDE:-/etc/nginx/conf.d/aitbc-hostname.conf}"
NGINX_BIN="${NGINX_BIN:-nginx}"
NGINX_RELOAD="${NGINX_RELOAD:-1}"
# writes to real /etc paths go through sudo so the script works run
# unprivileged too; scratch paths in rehearsals skip it.
SUDO=""
case "$NGINX_SITES_AVAILABLE" in
    /etc/*) SUDO="sudo -n" ;;
esac

# Detect node identity
NODE_HOSTNAME="$(hostname -f 2>/dev/null || hostname)"
# Derive domain from hub_discovery_url in aitbc config, fall back to env
AITBC_CONFIG="/etc/aitbc/node.env"
HUB_DISCOVERY_URL=""
if [[ -f "$AITBC_CONFIG" ]]; then
    HUB_DISCOVERY_URL="$(grep -E '^HUB_DISCOVERY_URL=' "$AITBC_CONFIG" | cut -d= -f2- | tr -d '"' || true)"
fi
# #1023: HUB_DISCOVERY_URL is documented as a URL (http://host:port) —
# strip scheme, port and path or the sed below would break on slashes.
HUB_HOST_RAW="${HUB_DISCOVERY_URL:-hub.aitbc.invalid}"
HUB_HOST="${HUB_HOST_RAW#*://}"
HUB_HOST="${HUB_HOST%%:*}"
HUB_HOST="${HUB_HOST%%/*}"
BASE_DOMAIN="${HUB_HOST#hub.}"

SERVER_NAME="${NODE_HOSTNAME}.${BASE_DOMAIN} ${NODE_HOSTNAME}"

echo "→ Node hostname : $NODE_HOSTNAME"
echo "→ Base domain   : $BASE_DOMAIN"
echo "→ nginx server_name: $SERVER_NAME"

# #1023: render into a temp file and test BEFORE touching the live site —
# the old order overwrote sites-available first and left the unsubstituted
# example behind on any sed/nginx failure.
TMP_CONF="$(mktemp)"
TMP_WRAPPER="$(mktemp)"
trap 'rm -f "$TMP_CONF" "$TMP_WRAPPER"' EXIT
sed "s/server_name _;/server_name ${SERVER_NAME};/" "$NGINX_CONF_SRC" > "$TMP_CONF"

# A site fragment needs an http{} context to be testable — wrap it.
cat > "$TMP_WRAPPER" <<OVREND
events {}
http {
    include ${TMP_CONF};
}
OVREND

"$NGINX_BIN" -t -q -c "$TMP_WRAPPER"

# Render passed: back up the live config, then move into place.
if [[ -f "$NGINX_SITES_AVAILABLE" ]]; then
    $SUDO cp -a "$NGINX_SITES_AVAILABLE" "${NGINX_SITES_AVAILABLE}.bak.$(date +%s)"
fi
$SUDO install -m 0644 "$TMP_CONF" "$NGINX_SITES_AVAILABLE"
$SUDO ln -sf "$NGINX_SITES_AVAILABLE" "$NGINX_SITES_ENABLED"

# Write per-node hostname override (nginx conf.d loads before sites)
$SUDO tee "$NGINX_OVERRIDE" >/dev/null <<OVREND
# Auto-generated by install-nginx-node.sh — do not edit manually
# Re-run the script after hostname/domain changes.
server_name_in_redirect off;
OVREND

# Test the full live config and reload only on success; a failure here
# restores the backup so a reload can never hit a broken site.
if ! "$NGINX_BIN" -t; then
    if ls "${NGINX_SITES_AVAILABLE}".bak.* >/dev/null 2>&1; then
        $SUDO cp -a "$(ls -t "${NGINX_SITES_AVAILABLE}".bak.* | head -1)" "$NGINX_SITES_AVAILABLE"
        echo "x nginx -t failed after install — previous site config restored" >&2
    fi
    exit 1
fi
if [[ "$NGINX_RELOAD" == "1" ]]; then
    sudo -n systemctl reload nginx
fi

echo ""
echo "✓ nginx configured for node: $SERVER_NAME"
echo ""
echo "Services now available at:"
echo "  http://${NODE_HOSTNAME}.${BASE_DOMAIN}/whisper/health"
echo "  http://${NODE_HOSTNAME}.${BASE_DOMAIN}/ollama/api/tags"
echo "  http://${NODE_HOSTNAME}.${BASE_DOMAIN}/rpc/"
echo "  http://${NODE_HOSTNAME}.${BASE_DOMAIN}/agent/health"
echo "  http://${NODE_HOSTNAME}.${BASE_DOMAIN}/ffmpeg/health"
